#!/usr/bin/env python3
"""
Joins the install files into ONE file, sql/install_all.sql, so setting up
Supabase is a single paste into the SQL Editor. Run it again after changing
any sql file:  python3 tools/build_install.py
"""
from pathlib import Path

SQL = Path(__file__).resolve().parent.parent / "sql"
FILES = ["01_schema", "02_constraints_and_indexes", "03_security", "04_seed_data",
         "06_views", "07_sources_and_notes", "08_sources_seed", "09_storage"]

out = ["-- =====================================================================",
       "-- TRACE · install_all.sql   (GENERATED by tools/build_install.py)",
       "-- Paste this whole file into the Supabase SQL Editor and press Run.",
       "-- It is the files " + ", ".join(f + ".sql" for f in FILES) + " in order.",
       "-- If it stops with an error, run sql/99_uninstall_trace.sql, then run this again.",
       "-- ====================================================================="]
for name in FILES:
    out += ["", f"-- ############ {name}.sql ############", (SQL / f"{name}.sql").read_text(encoding="utf-8")]
(SQL / "install_all.sql").write_text("\n".join(out), encoding="utf-8")
print(f"Wrote sql/install_all.sql ({(SQL / 'install_all.sql').stat().st_size // 1024} KB)")
