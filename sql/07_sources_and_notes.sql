-- =====================================================================
-- TRACE · 07_sources_and_notes.sql   (run after 06_views.sql)
-- Sources (photos, sketches, whiteboards, documents), notes on any
-- record, and annotation pins on a source image.
--
-- "Exclusive arc": a source or note can belong to a session OR any one of
-- the five evidence records. Each possible parent gets a real foreign
-- key column, and a CHECK makes sure exactly one of them is filled in.
-- (Storing a "type + id" pair instead would lose referential integrity.)
-- =====================================================================

begin;

create table public.source (
  id                bigint generated by default as identity primary key,
  title             text        not null,
  kind              text        not null default 'photo',
  caption           text,
  file_url          text        not null,            -- in PostgreSQL: a link to file storage, never the file itself
  is_illustration   boolean     not null default false, -- true for the drawn stand-ins in the sample study
  session_id        bigint references public.research_session (id) on delete cascade,
  observation_id    bigint references public.observation (id) on delete cascade,
  finding_id        bigint references public.finding (id) on delete cascade,
  insight_id        bigint references public.insight (id) on delete cascade,
  recommendation_id bigint references public.recommendation (id) on delete cascade,
  decision_id       bigint references public.design_decision (id) on delete cascade,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now(),
  constraint source_title_check check (char_length(btrim(title)) between 3 and 160),
  constraint source_kind_check check (kind in ('photo', 'whiteboard', 'sketch', 'notes', 'document', 'screenshot')),
  constraint source_caption_check check (caption is null or char_length(caption) <= 1000),
  constraint source_one_parent check (num_nonnulls(session_id, observation_id, finding_id, insight_id, recommendation_id, decision_id) = 1)
);

create table public.note (
  id                bigint generated by default as identity primary key,
  body              text        not null,
  author_id         bigint      not null references public.researcher (id) on delete restrict,
  session_id        bigint references public.research_session (id) on delete cascade,
  observation_id    bigint references public.observation (id) on delete cascade,
  finding_id        bigint references public.finding (id) on delete cascade,
  insight_id        bigint references public.insight (id) on delete cascade,
  recommendation_id bigint references public.recommendation (id) on delete cascade,
  decision_id       bigint references public.design_decision (id) on delete cascade,
  created_at        timestamptz not null default now(),
  constraint note_body_check check (char_length(btrim(body)) between 2 and 2000),
  constraint note_one_parent check (num_nonnulls(session_id, observation_id, finding_id, insight_id, recommendation_id, decision_id) = 1)
);

-- A pin on a source image. A weak entity: it only exists with its source.
create table public.annotation (
  id         bigint generated by default as identity primary key,
  source_id  bigint       not null references public.source (id) on delete cascade,
  x          numeric(5,4) not null,   -- 0 = left edge, 1 = right edge
  y          numeric(5,4) not null,   -- 0 = top, 1 = bottom
  body       text         not null,
  author_id  bigint       not null references public.researcher (id) on delete restrict,
  created_at timestamptz  not null default now(),
  constraint annotation_position_check check (x between 0 and 1 and y between 0 and 1),
  constraint annotation_body_check check (char_length(btrim(body)) between 2 and 500)
);

-- Indexes on every foreign key used for lookups
create index source_session_idx on public.source (session_id);
create index source_observation_idx on public.source (observation_id);
create index source_finding_idx on public.source (finding_id);
create index source_insight_idx on public.source (insight_id);
create index source_recommendation_idx on public.source (recommendation_id);
create index source_decision_idx on public.source (decision_id);
create index note_session_idx on public.note (session_id);
create index note_finding_idx on public.note (finding_id);
create index note_insight_idx on public.note (insight_id);
create index note_decision_idx on public.note (decision_id);
create index annotation_source_idx on public.annotation (source_id);

create trigger source_touch_updated_at before update on public.source
  for each row execute function public.trace_touch_updated_at();

-- Same access model as the other tables: everyone reads, editors write,
-- and editors may delete their notes and pins (but not sources' parents).
do $$
declare t text;
begin
  foreach t in array array['source', 'note', 'annotation'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon, authenticated', t);
    execute format('grant select on public.%I to anon, authenticated', t);
    execute format('grant insert, update, delete on public.%I to authenticated', t);
    execute format('create policy %I on public.%I for select to anon, authenticated using (true)', t || ': anyone can read', t);
    execute format('create policy %I on public.%I for insert to authenticated with check ((select public.trace_is_editor()))', t || ': editors can insert', t);
    execute format('create policy %I on public.%I for update to authenticated using ((select public.trace_is_editor())) with check ((select public.trace_is_editor()))', t || ': editors can update', t);
    execute format('create policy %I on public.%I for delete to authenticated using ((select public.trace_is_editor()))', t || ': editors can delete', t);
  end loop;
end $$;

-- Every source with the record it belongs to, as one readable list (CASE + COALESCE).
create view public.v_source_owner with (security_invoker = true) as
  select s.id, s.title, s.kind,
         case when s.session_id is not null then 'research_session'
              when s.observation_id is not null then 'observation'
              when s.finding_id is not null then 'finding'
              when s.insight_id is not null then 'insight'
              when s.recommendation_id is not null then 'recommendation'
              else 'design_decision' end as attached_to,
         coalesce(s.session_id, s.observation_id, s.finding_id, s.insight_id, s.recommendation_id, s.decision_id) as attached_id,
         (select count(*) from public.annotation a where a.source_id = s.id) as pins
    from public.source s;
grant select on public.v_source_owner to anon, authenticated;

commit;
