-- =====================================================================
-- TRACE · 01_schema.sql
-- Creates the TRACE tables (primary keys, NOT NULL columns, defaults).
-- Foreign keys, UNIQUE/CHECK constraints, indexes and triggers are in
-- 02_constraints_and_indexes.sql. Run the files in numeric order.
--
-- Safety: this script never drops anything. If any TRACE table already
-- exists it stops with an error and changes nothing.
-- =====================================================================

begin;

do $$
declare
  existing text;
begin
  select string_agg(table_name, ', ' order by table_name)
    into existing
    from information_schema.tables
   where table_schema = 'public'
     and table_name in (
       'researcher', 'segment', 'research_method', 'research_project',
       'project_researcher', 'project_method', 'participant',
       'participant_segment', 'research_question', 'research_session',
       'session_participant', 'session_question', 'observation', 'finding',
       'insight', 'recommendation', 'design_decision', 'observation_finding',
       'finding_insight', 'insight_recommendation', 'recommendation_decision',
       'trace_editor'
     );
  if existing is not null then
    raise exception 'TRACE tables already exist: %. Nothing was changed. Inspect them before re-installing (see sql/99_uninstall_trace.sql).', existing;
  end if;
end
$$;

-- ---------------------------------------------------------------------
-- Reference entities
-- ---------------------------------------------------------------------

create table public.researcher (
  id          bigint generated by default as identity primary key,
  full_name   text        not null,
  email       text        not null,
  role_title  text,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create table public.segment (
  id          bigint generated by default as identity primary key,
  name        text        not null,
  description text,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create table public.research_method (
  id          bigint generated by default as identity primary key,
  name        text        not null,
  description text,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- Projects
-- ---------------------------------------------------------------------

create table public.research_project (
  id                 bigint generated by default as identity primary key,
  title              text        not null,
  description        text,
  research_objective text        not null,
  status             text        not null default 'planned',
  start_date         date        not null,
  end_date           date,
  archived_at        timestamptz,            -- null = in use; set = archived
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now()
);

create table public.project_researcher (
  project_id    bigint      not null,
  researcher_id bigint      not null,
  project_role  text        not null default 'researcher',
  created_at    timestamptz not null default now(),
  primary key (project_id, researcher_id)
);

create table public.project_method (
  project_id bigint      not null,
  method_id  bigint      not null,
  created_at timestamptz not null default now(),
  primary key (project_id, method_id)
);

-- ---------------------------------------------------------------------
-- Participants (deliberately minimal personal information)
-- ---------------------------------------------------------------------

create table public.participant (
  id               bigint generated by default as identity primary key,
  participant_code text        not null,     -- e.g. P-07; never a real name
  age_band         text,
  notes            text,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);

create table public.participant_segment (
  participant_id bigint      not null,
  segment_id     bigint      not null,
  created_at     timestamptz not null default now(),
  primary key (participant_id, segment_id)
);

-- ---------------------------------------------------------------------
-- Questions and sessions
-- ---------------------------------------------------------------------

create table public.research_question (
  id            bigint generated by default as identity primary key,
  project_id    bigint      not null,
  question_text text        not null,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

create table public.research_session (
  id               bigint generated by default as identity primary key,
  project_id       bigint      not null,
  method_id        bigint      not null,
  researcher_id    bigint      not null,      -- facilitator
  title            text        not null,
  session_date     date        not null,
  duration_minutes integer,
  status           text        not null default 'planned',
  notes            text,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);

create table public.session_participant (
  session_id     bigint      not null,
  participant_id bigint      not null,
  created_at     timestamptz not null default now(),
  primary key (session_id, participant_id)
);

create table public.session_question (
  session_id  bigint      not null,
  question_id bigint      not null,
  created_at  timestamptz not null default now(),
  primary key (session_id, question_id)
);

-- ---------------------------------------------------------------------
-- Evidence records:
-- Observation -> Finding -> Insight -> Recommendation -> Design Decision
-- ---------------------------------------------------------------------

create table public.observation (
  id          bigint generated by default as identity primary key,
  session_id  bigint      not null,          -- the project is derived via the session
  title       text        not null,
  description text        not null,
  sentiment   text        not null default 'neutral',
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create table public.finding (
  id          bigint generated by default as identity primary key,
  project_id  bigint      not null,
  title       text        not null,
  description text        not null,
  confidence  text        not null default 'medium',
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create table public.insight (
  id          bigint generated by default as identity primary key,
  project_id  bigint      not null,
  title       text        not null,
  description text        not null,
  impact      text        not null default 'medium',
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create table public.recommendation (
  id          bigint generated by default as identity primary key,
  project_id  bigint      not null,
  title       text        not null,
  description text        not null,
  priority    text        not null default 'medium',
  status      text        not null default 'proposed',
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create table public.design_decision (
  id          bigint generated by default as identity primary key,
  project_id  bigint      not null,
  title       text        not null,
  description text        not null,          -- the rationale
  status      text        not null default 'proposed',
  decided_on  date,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- Evidence links (many-to-many at every step of the chain)

create table public.observation_finding (
  observation_id bigint      not null,
  finding_id     bigint      not null,
  created_at     timestamptz not null default now(),
  primary key (observation_id, finding_id)
);

create table public.finding_insight (
  finding_id bigint      not null,
  insight_id bigint      not null,
  created_at timestamptz not null default now(),
  primary key (finding_id, insight_id)
);

create table public.insight_recommendation (
  insight_id        bigint      not null,
  recommendation_id bigint      not null,
  created_at        timestamptz not null default now(),
  primary key (insight_id, recommendation_id)
);

create table public.recommendation_decision (
  recommendation_id bigint      not null,
  decision_id       bigint      not null,
  created_at        timestamptz not null default now(),
  primary key (recommendation_id, decision_id)
);

commit;
